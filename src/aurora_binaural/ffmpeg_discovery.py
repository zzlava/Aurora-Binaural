"""Shared, executable capability detection for setup and application entrypoints."""

from __future__ import annotations

import os
import shlex
import shutil
import subprocess
from functools import lru_cache
from pathlib import Path

from aurora_binaural.exit_codes import ProcessingError

LOCAL_ENV_PATH = Path(__file__).resolve().parents[2] / ".aurora-local.env"
HOMEBREW_FFMPEG_DIR = Path("/opt/homebrew/opt/ffmpeg-full/bin")
INSTALL_HINT = "On macOS run: brew install ffmpeg-full. On Linux install FFmpeg with --enable-libsoxr."


def read_local_config() -> dict[str, str]:
    """Read only our two literal assignments, never source or execute a shell file."""
    try:
        lines = LOCAL_ENV_PATH.read_text(encoding="utf-8").splitlines()
    except OSError:
        return {}
    result = {}
    for line in lines:
        key, sep, value = line.partition("=")
        if sep and key in ("AURORA_FFMPEG", "AURORA_FFPROBE"):
            try:
                words = shlex.split(value, comments=True)
            except ValueError:
                continue
            if len(words) == 1:
                result[key] = words[0]
    return result


@lru_cache(maxsize=16)
def _works(binary: str, soxr: bool) -> bool:
    args = (
        ["-nostdin", "-v", "error", "-f", "lavfi", "-i", "anullsrc=r=44100:cl=stereo", "-t", "0.01",
         "-af", "aresample=48000:resampler=soxr:precision=28", "-f", "null", "-"]
        if soxr else ["-version"]
    )
    try:
        return subprocess.run([binary, *args], capture_output=True, timeout=10, check=False).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def require_soxr(ffmpeg_bin: str) -> None:
    """Help output alone cannot prove that libsoxr was compiled in."""
    if not _works(ffmpeg_bin, True):
        raise ProcessingError(
            f"This FFmpeg cannot run soxr VHQ. {INSTALL_HINT} "
            "Set AURORA_FFMPEG to the installed binary. No lower-quality resampler was substituted.",
            error_code="SOXR_UNAVAILABLE",
        )


def discover_ffmpeg(*, soxr_required: bool = False) -> tuple[str, str]:
    local = read_local_config()
    selected: list[str] = []
    for name in ("ffmpeg", "ffprobe"):
        key = f"AURORA_{name.upper()}"
        override = os.environ.get(key)
        candidates = [override] if override else [local.get(key, ""), name, str(HOMEBREW_FFMPEG_DIR / name)]
        if name == "ffprobe" and not override:
            candidates.append(str(Path(selected[0]).with_name("ffprobe")))
        fallback = None
        for candidate in candidates:
            binary = shutil.which(candidate) if candidate else None
            if not binary or not _works(binary, False):
                continue
            if name == "ffmpeg" and not _works(binary, True):
                fallback = fallback or binary
                if not override:
                    continue
            selected.append(binary)
            break
        else:
            if fallback:
                selected.append(fallback)
            else:
                raise ProcessingError(
                    f"Required binary {key if override else name} was not found or could not run. {INSTALL_HINT}",
                    error_code="FFMPEG_NOT_FOUND",
                )
    if soxr_required:
        require_soxr(selected[0])
    return selected[0], selected[1]


def configure_local_ffmpeg() -> None:
    """Persist a validated selection, including paths with spaces, atomically."""
    try:
        ffmpeg, ffprobe = discover_ffmpeg(soxr_required=True)
    except ProcessingError as exc:
        raise SystemExit(exc.message) from exc
    content = "# Generated by scripts/setup.sh; read automatically by Aurora.\n"
    content += f"AURORA_FFMPEG={shlex.quote(ffmpeg)}\nAURORA_FFPROBE={shlex.quote(ffprobe)}\n"
    temporary = LOCAL_ENV_PATH.with_suffix(".env.tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(LOCAL_ENV_PATH)
    print(f"FFmpeg soxr resampling passed: {ffmpeg}\nFFprobe: {ffprobe}\nSaved {LOCAL_ENV_PATH.name}")
    print(f"If FFmpeg needs installing: {INSTALL_HINT}")
